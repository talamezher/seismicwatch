"""Profile each source before transforming it (Week 5): what is really in the raw files?

    python -m src.transform.profile        writes docs/profiling.md

For every column: type, % missing, number of distinct values, most common value,
min and max. Read-only: it never changes the raw layer.
"""
import json
from pathlib import Path

import pandas as pd

from src import config
from src.extract import geonames, wikipedia
from src.transform import staging


def profile(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for col in df.columns:
        s = df[col]
        try:
            distinct = s.nunique(dropna=True)
            common = s.mode(dropna=True)
            common = str(common.iloc[0])[:40] if len(common) else ""
        except TypeError:                       # lists or dicts in a column
            distinct, common = "-", ""
        num = pd.to_numeric(s, errors="coerce") if s.dtype != object else pd.Series(dtype=float)
        rows.append({"column": col, "type": str(s.dtype), "missing_pct": round(s.isna().mean() * 100, 1),
                     "distinct": distinct, "most_common": common,
                     "min": num.min() if num.notna().any() else "", "max": num.max() if num.notna().any() else ""})
    return pd.DataFrame(rows)


def main(out=None):
    out = Path(out or config.ROOT / "docs" / "profiling.md")
    parts = ["# Profiling of the raw sources\n",
             "Generated by `python -m src.transform.profile` from the raw layer, before any cleaning.\n"]

    raw = staging.read_usgs_raw(staging.usgs_raw_files())
    cols = [c for c in raw.columns if c.startswith("properties.") or c in ("id", "longitude", "latitude",
                                                                              "depth_km")]
    usgs = raw[cols].drop(columns=[c for c in cols if c.endswith((".url", ".detail", ".ids", ".sources",
                                                                  ".types", ".code", ".title"))])
    parts += [f"## USGS earthquake catalogue: {len(usgs):,} records\n", profile(usgs).to_markdown(index=False), ""]
    parts.append(f"- duplicated ids (versions across runs): {usgs['id'].duplicated().sum()}")
    parts.append(f"- depth exactly 10 km (USGS default): {(usgs['depth_km'] == 10).mean():.0%}")
    parts.append(f"- place text containing '?' (characters lost at the source): "
                 f"{usgs['properties.place'].str.contains('?', regex=False, na=False).sum()}\n")

    frames = [staging.read_geonames_zip(geonames.latest_file(n))
              for n in [*config.GEONAMES_COUNTRY_FILES, config.GEONAMES_NEIGHBOURS_FILE]]
    geo = pd.concat(frames, ignore_index=True)
    parts += [f"## GeoNames: {len(geo):,} lines in {len(frames)} files\n",
              profile(geo.drop(columns=["alternatenames"])).to_markdown(index=False), ""]
    p = geo[geo["feature_class"] == "P"]
    pop = pd.to_numeric(p["population"], errors="coerce")
    parts.append(f"- populated places (feature class P): {len(p):,}; population 0 (unknown): {(pop == 0).mean():.0%}")
    parts.append(f"- feature codes of populated places: "
                 + ", ".join(f"{k} {v:,}" for k, v in p["feature_code"].value_counts().head(8).items()))
    parts.append(f"- dem = -9999 (no data): {(geo['dem'] == '-9999').sum():,}")
    parts.append(f"- same geonameid in two files: {geo['geonameid'].duplicated().sum():,}\n")

    html = [(q.stem, q.read_text(encoding="utf-8")) for q in wikipedia.latest_pages()]
    tables = [t for _, h in html for t in wikipedia.earthquake_tables(h)]
    parts.append(f"## Wikipedia: {len(tables)} earthquake table(s), {sum(len(t) for t in tables)} rows\n")
    for i, t in enumerate(tables):
        parts.append(f"Table {i + 1}: {len(t)} rows, columns: " + ", ".join(staging._flat(c) for c in t.columns))
    wiki, acc = staging.stg_wiki_quakes(html)
    parts.append(f"\n- rows with a full date: {wiki['quake_date'].notna().sum()} of {len(wiki)}; "
                 f"magnitude unreadable: {wiki['magnitude'].isna().sum()}; duplicates: {acc['duplicates_removed']}")
    parts.append(f"- rows since the study start: {(wiki['quake_date'] >= config.STUDY_START).sum()}\n")

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
